"""Read Linux evdev input and stream the state the Noctalia overlay draws.

This helper is intentionally read-only. It never grabs, injects or logs input.
It opens only the keyboard and mouse selected in the plugin's device picker,
or the first suitable devices when no selection has been made.

The process needs read access to /dev/input/event*. The recommended setup is
the udev rule generated by code/setup-input-permissions.sh; adding the user to
the broad `input` group also works but grants access to every input device.
"""


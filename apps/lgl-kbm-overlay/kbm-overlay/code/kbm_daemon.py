KEYBOARD_PROBE = {30, 44, 57, 28}  # A, Z, Space, Enter
MOUSE_PROBE = {BTN_LEFT, BTN_RIGHT}

def key_name(code: int) -> str:
    if code in KEY_CODES:
        return KEY_CODES[code]
    if BTN_MISC <= code < BTN_JOYSTICK:
        return f"BTN_{code - BTN_MISC}"
    return f"KEY_{code}"

def _ioc(direction: int, kind: str, number: int, size: int) -> int:
    return (direction << 30) | (size << 16) | (ord(kind) << 8) | number

def _eviocgname(length: int = NAME_BYTES) -> int:
    return _ioc(2, "E", 0x06, length)

def _eviocgbit(ev: int, length: int) -> int:
    return _ioc(2, "E", 0x20 + ev, length)

def _bit_is_set(data: bytes, bit: int) -> bool:
    index = bit // 8
    if index >= len(data):
        return False
    return (data[index] & (1 << (bit % 8))) != 0

def _bits(data: bytes) -> set[int]:
    out: set[int] = set()
    for index, value in enumerate(data):
        while value:
            low = value & -value
            bit = low.bit_length() - 1
            out.add(index * 8 + bit)
            value &= value - 1
    return out

def _read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8", errors="replace").strip()
    except OSError:
        return None

def _sysfs_bits(path: str, capability: str) -> set[int]:
    """Read a capability bitmap from sysfs without opening the device.

    The kernel prints the bitmap as space-separated 64-bit words, most
    significant word first. Reversing the words makes the bit index equal to
    the evdev code, which lets the picker classify devices that the user cannot
    open yet.
    """
    event = Path(path).name
    raw = _read_text(Path("/sys/class/input") / event / "device" / "capabilities" / capability)
    if not raw:
        return set()
    bits: set[int] = set()
    for word_index, word in enumerate(reversed(raw.split())):
        try:
            value = int(word, 16)
        except ValueError:
            continue
        base = word_index * 64
        while value:
            low = value & -value
            bit = low.bit_length() - 1
            bits.add(base + bit)
            value &= value - 1
    return bits

def _sysfs_keys(path: str) -> set[int]:
    return _sysfs_bits(path, "key")

def _mouse_button_names(keys: set[int]) -> list[str]:
    present = {key_name(code) for code in keys}
    return [name for name in MOUSE_BUTTON_ORDER if name in present]

@dataclass
class Device:
    path: str
    name: str
    vendor: str = ""
    product: str = ""
    keyboard: bool = False
    mouse: bool = False
    buttons: list[str] = field(default_factory=list)
    readable: bool = True
    error: str | None = None

    def info(self) -> dict:
        return {
            "path": self.path,
            "name": self.name,
            "vendor": self.vendor,
            "product": self.product,
            "keyboard": self.keyboard,
            "mouse": self.mouse,
            "buttons": self.buttons,
            "readable": self.readable,
        }

def _sysfs_device(path: str) -> tuple[str, str, str]:
    event = Path(path).name
    base = Path("/sys/class/input") / event / "device"
    name = _read_text(base / "name") or event
    vendor = (_read_text(base / "id" / "vendor") or "").lower()
    product = (_read_text(base / "id" / "product") or "").lower()
    return name, vendor, product

def inspect_device(path: str) -> Device:
    name, vendor, product = _sysfs_device(path)
    device = Device(path=path, name=name, vendor=vendor, product=product)
    sysfs_keys = _sysfs_keys(path)
    sysfs_rel = _sysfs_bits(path, "rel")
    device.keyboard = bool(sysfs_keys & KEYBOARD_PROBE)
    # A mouse has relative X/Y axes. A tablet pad or macro pad may report
    # BTN_LEFT/RIGHT but no REL_X/REL_Y and should not be offered as a mouse.
    device.mouse = (not device.keyboard) and bool(sysfs_keys & MOUSE_PROBE) and bool(sysfs_rel & {0, 1})
    device.buttons = _mouse_button_names(sysfs_keys)
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
    except PermissionError:
        device.readable = False
        device.error = "permission"
        return device
    except OSError as error:
        device.readable = False
        device.error = str(error)
        return device
    try:
        raw_name = fcntl.ioctl(fd, _eviocgname(), bytes(NAME_BYTES))
        decoded = raw_name.split(b"\0", 1)[0].decode("utf-8", errors="replace").strip()
        if decoded:
            device.name = decoded
        keys = _bits(fcntl.ioctl(fd, _eviocgbit(EV_KEY, KEY_BYTES), bytes(KEY_BYTES)))
    except OSError as error:
        device.readable = False
        device.error = str(error)
        return device
    finally:
        os.close(fd)
    device.keyboard = bool(keys & KEYBOARD_PROBE)
    device.mouse = (not device.keyboard) and bool(keys & MOUSE_PROBE) and bool(sysfs_rel & {0, 1})
    device.buttons = _mouse_button_names(keys)
    return device

def discover() -> list[Device]:
    paths = sorted(Path("/dev/input").glob("event*"))
    out: list[Device] = []
    for path in paths:
        try:
            out.append(inspect_device(str(path)))
        except Exception as error:  # noqa: BLE001 - enumeration must not abort
            name, vendor, product = _sysfs_device(str(path))
            out.append(Device(
                path=str(path), name=name, vendor=vendor, product=product,
                readable=False, error=str(error),
            ))
    return out

def choose(devices: Iterable[Device], wanted: str | None, path_hint: str | None, kind: str) -> list[Device]:
    # Match a configured selection against all devices, including unreadable
    # ones, so a missing udev rule surfaces as a permission error instead of
    # silently switching to another keyboard or mouse.
    all_candidates = [d for d in devices if getattr(d, kind)]
    if kind == "mouse":
        # A keyboard with a few mouse-like buttons is still a keyboard. Never
        # offer it as a mouse just because it reports BTN_0 or a relative axis.
        all_candidates = [d for d in all_candidates if not d.keyboard]
    if not all_candidates:
        return []
    if wanted == "*":
        return [d for d in all_candidates if d.readable]
    if path_hint:
        for device in all_candidates:
            if device.path == path_hint:
                return [device]
    if wanted:
        exact = [d for d in all_candidates if d.name == wanted]
        if exact:
            return [exact[0]]
        folded = [d for d in all_candidates if d.name.casefold() == wanted.casefold()]
        if folded:
            return [folded[0]]
        # A selection that no longer exists should not fall back to a different
        # device. The status/error path tells the user to reconnect it.
        if path_hint or wanted:
            return []
    readable = [d for d in all_candidates if d.readable]
    if readable:
        return [readable[0]]
    # No readable candidate: return the first one so the reader can report a
    # specific permission error instead of a generic "no devices".
    return [all_candidates[0]]

class InputState:
    def __init__(self) -> None:
        self.pressed: set[str] = set()
        self.wheel_up = 0
        self.wheel_down = 0
        self.wheel_left = 0
        self.wheel_right = 0
        self.seq = 0
        self.dirty = False

    def handle(self, ev_type: int, code: int, value: int) -> None:
        if ev_type == EV_KEY:
            name = key_name(code)
            if value == 0:
                if name in self.pressed:
                    self.pressed.discard(name)
                    self.dirty = True
            elif value == 1:
                if name not in self.pressed:
                    self.pressed.add(name)
                    self.dirty = True
            # value 2 is autorepeat: the key is already held.
        elif ev_type == EV_REL:
            if code == REL_WHEEL:
                if value > 0:
                    self.wheel_up += value
                elif value < 0:
                    self.wheel_down += -value
                self.dirty = True
            elif code == REL_HWHEEL:
                if value > 0:
                    self.wheel_right += value
                elif value < 0:
                    self.wheel_left += -value
                self.dirty = True

    def snapshot(self, keyboard: list[Device], mouse: list[Device]) -> dict:
        self.seq += 1
        self.dirty = False
        keyboard_info = None
        if keyboard:
            keyboard_info = {
                "name": keyboard[0].name if len(keyboard) == 1 else "All keyboards",
                "path": keyboard[0].path if len(keyboard) == 1 else "",
                "count": len(keyboard),
            }
        mouse_info = None
        if mouse:
            buttons: list[str] = []
            for device in mouse:
                for name in device.buttons:
                    if name not in buttons:
                        buttons.append(name)
            mouse_info = {
                "name": mouse[0].name if len(mouse) == 1 else "All mice",
                "path": mouse[0].path if len(mouse) == 1 else "",
                "count": len(mouse),
                "buttons": buttons,
            }
        return {
            "type": "state",
            "pressed": sorted(self.pressed),
            "wheel_up": self.wheel_up,
            "wheel_down": self.wheel_down,
            "wheel_left": self.wheel_left,
            "wheel_right": self.wheel_right,
            "keyboard": keyboard_info,
            "mouse": mouse_info,
            "seq": self.seq,
            "ts": time.time(),
        }

class Reader:
    def __init__(self, config: dict, rate: int = 60) -> None:
        self.config = config
        self.rate = max(10, min(240, rate))
        self.interval = 1.0 / self.rate
        self.state = InputState()
        self.devices: list[Device] = []
        self.keyboards: list[Device] = []
        self.mice: list[Device] = []
        self.fds: dict[int, Device] = {}
        self.buffers: dict[int, bytearray] = {}
        self.running = True
        self.last_emit = 0.0
        self.last_scan = 0.0
        self.last_status: tuple | None = None
        self.last_error: tuple | None = None
        self.last_devices_key: str | None = None

    def emit(self, payload: dict) -> None:
        try:
            sys.stdout.write(json.dumps(payload, separators=(",", ":")) + "\n")
            sys.stdout.flush()
        except (BrokenPipeError, OSError):
            self.running = False

    def emit_error(self, code: str, message: str, device: Device | None = None) -> None:
        key = (code, device.path if device else "", message)
        if key == self.last_error:
            return
        self.last_error = key
        payload = {"type": "error", "code": code, "message": message}
        if device is not None:
            payload["device"] = device.name
            payload["path"] = device.path
        self.emit(payload)

    def scan(self, force: bool = False) -> None:
        now = time.monotonic()
        if not force and now - self.last_scan < 2.0:
            return
        self.last_scan = now
        self.devices = discover()
        info = [d.info() for d in self.devices]
        fingerprint = json.dumps(info, sort_keys=True, separators=(",", ":"))
        if fingerprint != self.last_devices_key:
            self.last_devices_key = fingerprint
            self.emit({"type": "devices", "devices": info})

        keyboard = choose(
            self.devices,
            self.config.get("keyboard") or "",
            self.config.get("keyboard_path") or "",
            "keyboard",
        )
        mouse = choose(
            self.devices,
            self.config.get("mouse") or "",
            self.config.get("mouse_path") or "",
            "mouse",
        )
        self.set_devices(keyboard, mouse)

    def set_devices(self, keyboards: list[Device], mice: list[Device]) -> None:
        wanted = {d.path for d in keyboards + mice}
        previous = {device.path for device in self.fds.values()}
        for fd, device in list(self.fds.items()):
            if device.path not in wanted:
                self.close_fd(fd)
        if previous != wanted:
            # A removed device may have left keys held. Do not show stuck keys.
            self.state.pressed.clear()
            self.state.dirty = True
        self.keyboards = keyboards
        self.mice = mice
        for device in keyboards + mice:
            if any(existing.path == device.path for existing in self.fds.values()):
                continue
            self.open_device(device)
        status = (
            tuple(d.path for d in keyboards),
            tuple(d.path for d in mice),
            bool(keyboards),
            bool(mice),
        )
        if status != self.last_status:
            self.last_status = status
            self.emit({
                "type": "status",
                "state": "ok" if (keyboards or mice) else "no_devices",
                "keyboard": keyboards[0].name if len(keyboards) == 1 else ("All keyboards" if keyboards else None),
                "mouse": mice[0].name if len(mice) == 1 else ("All mice" if mice else None),
            })
        if not keyboards and not mice:
            self.emit_error("no_devices", "No readable keyboard or mouse was found.")
        else:
            self.last_error = None
            self.state.dirty = True

    def open_device(self, device: Device) -> None:
        if not device.readable:
            if device.error == "permission":
                self.emit_error(
                    "permission",
                    f"Permission denied while opening {device.name}. Apply the udev rule and replug the device.",
                    device,
                )
            return
        try:
            fd = os.open(device.path, os.O_RDONLY | os.O_NONBLOCK)
        except PermissionError:
            self.emit_error(
                "permission",
                f"Permission denied while opening {device.name}. Apply the udev rule and replug the device.",
                device,
            )
            return
        except OSError as error:
            self.emit_error("open", f"Could not open {device.name}: {error}", device)
            return
        self.fds[fd] = device
        self.buffers[fd] = bytearray()

    def close_fd(self, fd: int) -> None:
        try:
            os.close(fd)
        except OSError:
            pass
        self.fds.pop(fd, None)
        self.buffers.pop(fd, None)

    def read_fd(self, fd: int) -> None:
        try:
            chunk = os.read(fd, 8192)
        except BlockingIOError:
            return
        except OSError:
            self.close_fd(fd)
            return
        if not chunk:
            self.close_fd(fd)
            return
        buffer = self.buffers.setdefault(fd, bytearray())
        buffer.extend(chunk)
        while len(buffer) >= EVENT_SIZE:
            _, _, ev_type, code, value = EVENT.unpack_from(buffer, 0)
            del buffer[:EVENT_SIZE]
            if ev_type != EV_SYN:
                self.state.handle(ev_type, code, value)

    def emit_state(self) -> None:
        self.emit(self.state.snapshot(self.keyboards, self.mice))

    def run(self) -> None:
        self.scan(force=True)
        while self.running:
            now = time.monotonic()
            if now - self.last_scan >= 2.0:
                self.scan()
            fds = list(self.fds)
            if fds:
                ready, _, _ = select.select(fds, [], [], self.interval)
                for fd in ready:
                    self.read_fd(fd)
            else:
                time.sleep(self.interval)
            now = time.monotonic()
            if self.state.dirty or now - self.last_emit >= 1.0:
                self.emit_state()
                self.last_emit = now

    def stop(self) -> None:
        self.running = False
        for fd in list(self.fds):
            self.close_fd(fd)

def load_config(path: str | None) -> dict:
    if not path:
        return {}
    try:
        with open(path, "r", encoding="utf-8") as handle:
            value = json.load(handle)
    except (OSError, ValueError):
        return {}
    return value if isinstance(value, dict) else {}

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Read evdev input for LGL KBM Overlay")
    parser.add_argument("--config", default="", help="JSON device selection file")
    parser.add_argument("--rate", type=int, default=60, help="state updates per second (10-240)")
    parser.add_argument("--pid-file", default="", help="write the reader PID here for stale-process cleanup")
    parser.add_argument("--list", action="store_true", help="print discovered devices and exit")
    args = parser.parse_args(argv)

    if args.list:
        print(json.dumps({"type": "devices", "devices": [d.info() for d in discover()]}, separators=(",", ":")))
        return 0

    if args.pid_file:
        try:
            Path(args.pid_file).write_text(str(os.getpid()) + "\n", encoding="ascii")
        except OSError:
            pass

    reader = Reader(load_config(args.config), rate=args.rate)

    def stop(_signum, _frame):
        reader.stop()

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    try:
        reader.run()
    finally:
        reader.stop()
        if args.pid_file:
            try:
                Path(args.pid_file).unlink()
            except OSError:
                pass
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

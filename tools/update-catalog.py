"""Generate or check the root catalog.toml from the root plugin manifests.

Noctalia git sources read catalog.toml from the repository root. The per-plugin
plugin.toml remains authoritative; this script only mirrors the catalog fields.

Usage:
    ./tools/update-catalog.py
    ./tools/update-catalog.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG = REPO_ROOT / "catalog.toml"
SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+$")
NON_PLUGIN_DIRS = {"dev", "tools", "LICENSES", ".git"}


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def quote_list(values: list[str]) -> str:
    return "[" + ", ".join(quote(value) for value in values) + "]"


def load_manifest(path: Path) -> dict:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def plugin_manifests() -> list[tuple[Path, dict]]:
    manifests: list[tuple[Path, dict]] = []
    for path in sorted(REPO_ROOT.glob("*/plugin.toml")):
        plugin_dir = path.parent
        if plugin_dir.name in NON_PLUGIN_DIRS:
            continue
        manifests.append((plugin_dir, load_manifest(path)))
    return manifests


def validate(plugin_dir: Path, manifest: dict) -> list[str]:
    errors: list[str] = []
    plugin_id = manifest.get("id")
    if not isinstance(plugin_id, str) or "/" not in plugin_id:
        errors.append(f"{plugin_dir}/plugin.toml: id must be '<author>/<plugin>'")
        return errors
    suffix = plugin_id.split("/", 1)[1]
    if suffix != plugin_dir.name:
        errors.append(
            f"{plugin_dir}/plugin.toml: id suffix {suffix!r} does not match directory {plugin_dir.name!r}"
        )
    version = manifest.get("version")
    if not isinstance(version, str) or not SEMVER_RE.fullmatch(version):
        errors.append(f"{plugin_dir}/plugin.toml: version must be MAJOR.MINOR.PATCH")
    plugin_api = manifest.get("plugin_api")
    if not isinstance(plugin_api, int) or isinstance(plugin_api, bool) or plugin_api <= 0:
        errors.append(f"{plugin_dir}/plugin.toml: plugin_api must be a positive integer")
    for field in ("name", "author", "license", "icon", "description"):
        if not isinstance(manifest.get(field), str) or not manifest[field].strip():
            errors.append(f"{plugin_dir}/plugin.toml: {field} must be a non-empty string")
    for field in ("tags", "dependencies"):
        if not isinstance(manifest.get(field), list):
            errors.append(f"{plugin_dir}/plugin.toml: {field} must be a list")
    return errors


def render(manifests: list[tuple[Path, dict]]) -> str:
    rows: list[str] = [
        "# This file is generated by tools/update-catalog.py.",
        "# The per-plugin plugin.toml stays authoritative.",
        "",
    ]
    for _plugin_dir, manifest in manifests:
        rows.append("[[plugin]]")
        rows.append(f"id           = {quote(manifest['id'])}")
        rows.append(f"name         = {quote(manifest['name'])}")
        rows.append(f"version      = {quote(manifest['version'])}")
        rows.append(f"author       = {quote(manifest['author'])}")
        rows.append(f"license      = {quote(manifest['license'])}")
        rows.append(f"icon         = {quote(manifest['icon'])}")
        rows.append(f"description  = {quote(manifest['description'])}")
        rows.append(f"plugin_api   = {manifest['plugin_api']}")
        rows.append(f"tags         = {quote_list(manifest['tags'])}")
        rows.append(f"dependencies = {quote_list(manifest['dependencies'])}")
        rows.append("")
    return "\n".join(rows).rstrip() + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if catalog.toml is out of date")
    args = parser.parse_args(argv)

    manifests = plugin_manifests()
    if not manifests:
        print("error: no root-level plugin manifests found", file=sys.stderr)
        return 1

    errors: list[str] = []
    for plugin_dir, manifest in manifests:
        errors.extend(validate(plugin_dir, manifest))
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1

    expected = render(manifests)
    current = CATALOG.read_text(encoding="utf-8") if CATALOG.is_file() else ""

    if args.check:
        if current != expected:
            print("error: catalog.toml is out of date; run ./tools/update-catalog.py", file=sys.stderr)
            return 1
        print(f"catalog.toml is up to date ({len(manifests)} plugins).")
        return 0

    CATALOG.write_text(expected, encoding="utf-8")
    print(f"wrote {CATALOG} ({len(manifests)} plugins).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
